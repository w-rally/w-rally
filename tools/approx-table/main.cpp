// approx-table: the rcpss table of phys::num::RcpApproxBits (modules/physics-rbr/src/num/approx.h), captured from the
// running CPU, and a check of the built-in table against the running CPU.
//
//   approx-table --capture <out.inc> "<cpu label>"   capture the table (top 12 mantissa bits at exponent 127), check
//                                                    that table + exponent rescale + the special cases reproduce this
//                                                    CPU's rcpss and rcpps on all 2^32 inputs, and write the .inc
//   approx-table --verify                            count the inputs where RcpApproxBits differs from this CPU's
//                                                    rcpss (0 on the table's source CPU; other vendors differ)
//   approx-table --self-test                         RcpApproxBits against fixed AMD results (any CPU: the test)
#include "num/approx.h"

#include <immintrin.h>

#include <cstdint>
#include <cstdio>
#include <cstring>
#include <vector>

namespace {

constexpr int kBits = 12;

uint32_t HwRcp(uint32_t x)
{
    return static_cast<uint32_t>(_mm_cvtsi128_si32(
        _mm_castps_si128(_mm_rcp_ss(_mm_castsi128_ps(_mm_cvtsi32_si128(static_cast<int>(x)))))));
}

// The same rule as RcpApproxBits, over a given table.
uint32_t Model(const std::vector<uint32_t>& t, uint32_t x)
{
    const uint32_t exp = (x >> 23) & 0xff, sign = x & 0x80000000u;
    if (exp == 0xff) return (x & 0x007fffffu) ? (x | 0x00400000u) : sign;
    if (exp == 0) return sign | 0x7f800000u;
    const uint32_t ref = t[(x & 0x007fffffu) >> (23 - kBits)];
    const int32_t re = static_cast<int32_t>((ref >> 23) & 0xff) - (static_cast<int32_t>(exp) - 127);
    if (re <= 0) return sign;
    return sign | (ref & 0x007fffffu) | (static_cast<uint32_t>(re) << 23);
}

int Capture(const char* path, const char* label)
{
    std::vector<uint32_t> t(1u << kBits);
    for (uint32_t k = 0; k < t.size(); ++k) t[k] = HwRcp(0x3f800000u | (k << (23 - kBits)));
    uint64_t bad = 0, badPs = 0;
    for (uint64_t x = 0; x < (1ull << 32); x += 4) {
        const __m128i v = _mm_setr_epi32(static_cast<int>(x), static_cast<int>(x + 1), static_cast<int>(x + 2),
                                         static_cast<int>(x + 3));
        uint32_t ps[4];
        _mm_storeu_si128(reinterpret_cast<__m128i*>(ps), _mm_castps_si128(_mm_rcp_ps(_mm_castsi128_ps(v))));
        for (uint32_t i = 0; i < 4; ++i) {
            const uint32_t xi = static_cast<uint32_t>(x + i), hw = HwRcp(xi);
            if (Model(t, xi) != hw) {
                if (!bad) std::printf("first mismatch: x %08x rcpss %08x table %08x\n", xi, hw, Model(t, xi));
                ++bad;
            }
            if (ps[i] != hw) ++badPs;
        }
    }
    std::printf("table + rule against rcpss: %llu of 2^32 differ; rcpps against rcpss: %llu differ\n",
                static_cast<unsigned long long>(bad), static_cast<unsigned long long>(badPs));
    if (bad || badPs) return 1;
    FILE* f = std::fopen(path, "wb");
    if (!f) { std::printf("cannot write %s\n", path); return 1; }
    std::fprintf(f, "// Generated by tools/approx-table (approx-table --capture) - do not edit.\n");
    std::fprintf(f, "// rcpss result table captured on: %s\n", label);
    std::fprintf(f, "// Verified on that CPU: table + exponent rescale + the special cases reproduce rcpss and rcpps on all\n");
    std::fprintf(f, "// 2^32 inputs.\n");
    std::fprintf(f, "constexpr int kRcpTableBits = %d;\n", kBits);
    std::fprintf(f, "constexpr const char* kRcpTableSource = \"%s\";\n", label);
    std::fprintf(f, "constexpr uint32_t kRcpTable[%zu] = {\n", t.size());
    for (size_t i = 0; i < t.size(); i += 8) {
        std::fprintf(f, "   ");
        for (size_t j = i; j < i + 8; ++j) std::fprintf(f, " 0x%08x,", t[j]);
        std::fprintf(f, "\n");
    }
    std::fprintf(f, "};\n");
    std::fclose(f);
    std::printf("wrote %s (%zu entries)\n", path, t.size());
    return 0;
}

int Verify()
{
    uint64_t diff = 0;
    for (uint64_t x = 0; x < (1ull << 32); ++x) {
        const uint32_t xi = static_cast<uint32_t>(x);
        if (phys::num::RcpApproxBits(xi) != HwRcp(xi)) {
            if (!diff) std::printf("first difference: x %08x this CPU %08x table %08x\n", xi, HwRcp(xi),
                                   phys::num::RcpApproxBits(xi));
            ++diff;
        }
    }
    std::printf("RcpApproxBits (%s) against this CPU's rcpss: %llu of 2^32 differ\n", phys::num::RcpApproxSource(),
                static_cast<unsigned long long>(diff));
    return diff ? 1 : 0;
}

// rcpss on the AMD Ryzen 7 PRO 8840HS, and the special cases. The first rows are where an Intel i7-4790K differs
// (3eaaa000, 3f4f5800, 3f802800).
int SelfTest()
{
    struct Case { uint32_t x, r; };
    static const Case cases[] = {
        {0x40400000u, 0x3eaaa800u}, {0x3f9e0419u, 0x3f4f6000u}, {0x3f7fbe77u, 0x3f802000u},
        {0x3f800000u, 0x3f7ff000u}, {0x3f000000u, 0x3ffff000u}, {0x40000000u, 0x3efff000u},
        {0x40e00000u, 0x3e124000u}, {0x42c80000u, 0x3c23d000u}, {0xc0400000u, 0xbeaaa800u},
        {0x00000000u, 0x7f800000u}, {0x80000000u, 0xff800000u}, {0x00000001u, 0x7f800000u},
        {0x807fffffu, 0xff800000u}, {0x7f800000u, 0x00000000u}, {0xff800000u, 0x80000000u},
        {0x7fc00000u, 0x7fc00000u}, {0x7f800001u, 0x7fc00001u}, {0xff812345u, 0xffc12345u},
        {0x7f7fffffu, 0x00000000u}, {0x7e800000u, 0x00000000u}, {0x7e7fffffu, 0x00800000u},
    };
    int bad = 0;
    for (const Case& c : cases) {
        const uint32_t r = phys::num::RcpApproxBits(c.x);
        if (r != c.r) {
            std::printf("rcp %08x: %08x, AMD %08x\n", c.x, r, c.r);
            ++bad;
        }
    }
    std::printf("rcp table (%s): %d of %zu cases differ\n", phys::num::RcpApproxSource(), bad,
                sizeof(cases) / sizeof(cases[0]));
    return bad ? 1 : 0;
}

} // namespace

int main(int argc, char** argv)
{
    if (argc == 4 && !std::strcmp(argv[1], "--capture")) return Capture(argv[2], argv[3]);
    if (argc == 2 && !std::strcmp(argv[1], "--verify")) return Verify();
    if (argc == 2 && !std::strcmp(argv[1], "--self-test")) return SelfTest();
    std::printf("usage: approx-table --capture <out.inc> \"<cpu label>\" | --verify | --self-test\n");
    return 2;
}
